"""Render results/*.json into results/EVAL_REPORT.md (handles several models side by side)."""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import RESULTS_DIR

SQL_LABEL = {
    "schema_only": "A. table/column names and types only",
    "semantic_retry": "B. + dbt semantic layer (descriptions, business rules, 2 examples) + retry",
}


def _load(name: str) -> dict | None:
    path = RESULTS_DIR / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _files(prefix: str) -> list[dict]:
    def order(path: Path) -> tuple:   # local runs first, then by model size (3b, 7b, 14b)
        size = re.search(r"_(\d+)b", path.stem)
        return ("openai" in path.stem, int(size.group(1)) if size else 0, path.stem)

    out = []
    for path in sorted(RESULTS_DIR.glob(f"{prefix}*.json"), key=order):
        if "oracle" in path.name:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        out.append(data)
    return out


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x * 100:.1f}%"


def _model(cfg: dict) -> str:
    return cfg["model"].replace("openai-compatible:", "vLLM: ").replace("ollama:", "Ollama: ")


def render() -> str:
    out = ["# Evaluation report", "",
           "Generated by `python -m erp_copilot.evaluation report` from the JSON files in this folder. "
           "The question sets (`eval/`) were written by the project author, who also designed the system, so the "
           "numbers may overestimate accuracy on real users' questions.", ""]
    out += _in_house_sql() + _in_house_retrieval()
    return "\n".join(out)


def _in_house_sql() -> list[str]:
    runs = _files("eval_sql_")
    if not runs:
        return []
    out = ["## In-house Text-to-SQL (36 questions, `eval/golden_sql.yaml`)", "",
           "Correct = the result set matches the reference query. *Strict*: same rows and columns (row order ignored, "
           "numbers rounded to 2 decimals). *Lenient*: also accepts extra helper columns or a different column order.", "",
           "| Model | Prompt configuration | Executable | Strict | Lenient (1st attempt) | Lenient (with retry) | p50 / p95 latency |",
           "|---|---|---|---|---|---|---|"]
    for run in runs:
        for name, cfg in run["configs"].items():
            s = cfg["summary"]
            retry = _pct(s["lenient_acc"]) if cfg["max_attempts"] > 1 else "—"
            out.append(f"| {_model(cfg)} | {SQL_LABEL.get(name, name)} | {_pct(s['executable_rate'])} | "
                       f"{_pct(s['strict_acc'])} | {_pct(s['first_attempt_acc'])} | {retry} | "
                       f"{s['latency_p50_s']}s / {s['latency_p95_s']}s |")
    out += ["", "Machines: " + "; ".join(f"`{r['_file']}`: {r['meta']['machine']}, {r['meta']['generated_at']}" for r in runs), ""]
    first = runs[0]
    best = first["configs"].get("semantic_retry") or next(iter(first["configs"].values()))
    misses = [i for i in best["items"] if not i["lenient"]]
    if misses:
        out += [f"Questions answered incorrectly by {_model(best)} with configuration B:", ""]
        for i in misses:
            reason = i["outcome"] + (f": {i['last_error'][:120]}" if i.get("last_error") and i["outcome"] != "wrong_result" else "")
            out.append(f"- `{i['id']}` {i['question']} — {reason}")
        out.append("")
    return out


def _in_house_retrieval() -> list[str]:
    ret = _load("eval_retrieval.json")
    if not ret:
        return []
    meta = ret["meta"]
    out = ["## In-house SOP retrieval (26 questions, `eval/golden_sop.yaml`)", "",
           f"{meta['chunks']} chunks; {ret['modes'].get('bm25', {}).get('n_paraphrase', 0)} questions are paraphrased so they "
           f"share few words with the document. Embeddings: `{meta.get('embed_model')}` · {meta['generated_at']}", "",
           "| Retriever | Hit@1 | Hit@3 | MRR | Hit@3 on paraphrased questions |", "|---|---|---|---|---|"]
    label = {"bm25": "BM25 (character bigrams)", "dense": "Dense (embeddings)", "hybrid": "Hybrid (RRF of both)"}
    for mode, m in ret["modes"].items():
        out.append(f"| {label.get(mode, mode)} | {_pct(m['hit@1'])} | {_pct(m['hit@3'])} | {m['mrr']:.3f} "
                   f"| {_pct(m['paraphrase_hit@3'])} |")
    return out + [""]


__all__ = ["render", "Path"]
